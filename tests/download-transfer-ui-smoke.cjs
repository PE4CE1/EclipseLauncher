const { app, BrowserWindow, ipcMain, session, net } = require('electron')
const fs = require('node:fs'), path = require('node:path'), http = require('node:http'), assert = require('node:assert/strict')
const loadTs = require('./download-loader.cjs'), wait = ms => new Promise(resolve => setTimeout(resolve, ms))
const root = path.join(__dirname, '..'), output = path.join(root, '.cache/download-transfer-ui')
app.setPath('userData', process.env.ECLIPSE_SMOKE_TEMP); app.setPath('sessionData', process.env.ECLIPSE_SMOKE_TEMP)
app.on('window-all-closed', () => {})
app.whenReady().then(async () => {
  fs.mkdirSync(output, { recursive: true })
  const body = Buffer.alloc(8 * 1024 ** 2, 67), ranges = [], controls = [], errors = []
  let failCancel = false, window, lastPayload
  const server = http.createServer((req, res) => {
    const offset = Number(/^bytes=(\d+)-/.exec(req.headers.range || '')?.[1]) || 0
    res.writeHead(offset ? 206 : 200, { 'Content-Type': 'application/zip', 'Content-Length': body.length - offset, ...(offset ? { 'Content-Range': `bytes ${offset}-${body.length - 1}/${body.length}` } : {}) })
    if (req.method === 'HEAD') return res.end()
    ranges.push(offset); let position = offset
    const timer = setInterval(() => { const end = Math.min(body.length, position + (Date.now() % 2000 < 1000 ? 8192 : 24576)); res.write(body.subarray(position, end)); position = end; if (position === body.length) { clearInterval(timer); res.end() } }, 35)
    res.once('close', () => clearInterval(timer))
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const url = `http://127.0.0.1:${server.address().port}/fixture.zip`, directory = path.join(process.env.ECLIPSE_SMOKE_TEMP, 'downloads')
  ipcMain.on('account:get-identity-sync', event => { event.returnValue = null })
  ipcMain.handle('settings:set', () => ({ success: true }))
  ipcMain.handle('sources:get-all-cached', () => [])
  for (const action of ['pause', 'resume', 'cancel']) ipcMain.handle('torrent:' + action, () => { throw new Error('HTTP control must never reach the torrent engine') })
  const service = loadTs({ electron: { app, session, net }, './linkResolverService': { resolveDownloadLink: async streamUrl => ({ type: 'http', streamUrl }) }, './extractService': { extractArchive: async () => { throw new Error('Extraction forbidden in fixture') } } })('electron/httpDownloadService.ts')
  service.initHttpDownloadIPC({ handle: (name, fn) => ipcMain.handle(name, async (...args) => {
    if (/http-download:(pause|resume|cancel)/.test(name)) controls.push(name)
    if (name === 'http-download:cancel' && failCancel) { failCancel = false; throw new Error('Fixture rejected cancel') }
    return fn(...args)
  }) }, { isDestroyed: () => false, webContents: { send: (channel, payload) => { lastPayload = payload; window?.webContents.send(channel, payload) } } })
  session.defaultSession.webRequest.onBeforeRequest((details, done) => done({ cancel: /^https?:/.test(details.url) && !details.url.startsWith('http://127.0.0.1:') }))
  window = new BrowserWindow({ show: false, width: 1280, height: 880, webPreferences: { preload: path.join(root, 'dist-electron/preload.js'), sandbox: true, contextIsolation: true, backgroundThrottling: false } })
  window.webContents.on('console-message', event => { if (event.level === 'error' && !/ERR_|Failed to load resource/.test(event.message)) errors.push(event.message) })
  const evaluate = code => window.webContents.executeJavaScript(code, true)
  const until = async code => { const end = Date.now() + 6000; while (Date.now() < end) { if (await evaluate(code)) return; await wait(40) } throw new Error('Transfer UI timeout: ' + code) }
  const capture = async name => { let image; for (let i = 0; i < 10; i++) { try { window.webContents.invalidate(); image = await window.webContents.capturePage() } catch (error) { if (!/UnknownVizError/.test(String(error)) || i === 9) throw error } await wait(40) } fs.writeFileSync(path.join(output, name + '.png'), image.toPNG()) }
  await window.loadFile(path.join(root, '.cache/download-ui/fixture/tests/download-fixture.html'))
  await until('!!window.__downloadsFixture')
  const result = await evaluate(`window.__downloadsFixture.native(${JSON.stringify(url)},${JSON.stringify(directory)})`)
  assert.equal(result.success, true)
  await until('!!document.querySelector(".download-graph-line")')
  await wait(2100); await capture('downloading')
  await evaluate('document.querySelector(".download-transfer-button").click();document.querySelector(".download-transfer-button").click();true')
  await until('!!document.querySelector(".download-task[data-status=paused]")')
  assert.equal(controls.filter(name => name.endsWith(':pause')).length, 1, 'Rapid double click issues only one command')
  await wait(150)
  const file = path.join(directory, fs.readdirSync(directory)[0]), bytesPaused = fs.statSync(file).size
  const pausedPath = await evaluate('document.querySelector(".download-graph-line").getAttribute("d")')
  await wait(1100)
  assert.equal(fs.statSync(file).size, bytesPaused, 'No disk writes during pause')
  assert.equal(await evaluate('document.querySelector(".download-graph-line").getAttribute("d")'), pausedPath)
  await capture('paused')
  await evaluate('document.querySelector(".download-transfer-button").click();true')
  await until('!!document.querySelector(".download-task[data-status=downloading]")')
  await wait(1100)
  assert.equal(ranges.at(-1), bytesPaused, 'Resume uses real flushed file offset')
  failCancel = true
  await evaluate('document.querySelector(".download-task-actions .download-icon-button").click();true')
  await until('!!document.querySelector(".download-control-error")')
  assert.equal(await evaluate('document.querySelectorAll(".download-task").length'), 1, 'Rejected cancel must not remove a running job')
  await evaluate('document.querySelector(".download-task-actions .download-icon-button").click();true')
  await until('document.querySelectorAll(".download-task").length===0')
  assert.equal(fs.existsSync(file), false)
  window.webContents.send('torrent:progress', lastPayload)
  await wait(100)
  assert.equal(await evaluate('document.querySelectorAll(".download-task").length'), 0, 'Late event cannot resurrect a cancelled job')
  assert.deepEqual(errors, [])
  fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify({ realHttp: true, realPreload: true, measuredGraph: true, rapidPauseSingleCommand: true, pausedBytesStable: true, pausedGraphStable: true, rangeResume: bytesPaused, rejectedCancelVisible: true, cancelledFileRemoved: true, noResurrection: true, controls, rendererErrors: errors }, null, 2))
  service.stopHttpDownloads(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve))
  window.destroy(); app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
setTimeout(() => { console.error('Transfer UI fixture timeout'); app.exit(1) }, 45000).unref()
