  await until(()=>settings().crosshairConfig?.imageSize===76)
  await until(()=>hud.webContents.executeJavaScript('document.querySelector("#widget-crosshair svg image")?.getAttribute("width")==="76"'))
  assert.equal(settings().crosshairConfig.imageData,data,'Scaling must not re-encode or flatten the animation')
  await click('[data-crosshair-move=right]')
  await click('[data-crosshair-move=up]')
