  assert.ok(await evaluate('document.activeElement===document.querySelector("[data-crosshair-category-trigger]")'),'Escape restores keyboard focus')
  await click('[data-library-crosshair$="/soyjak-pointing-45631/"]')
  await until(()=>settings().crosshairConfig?.imageSource===origin+'/crosshairs/soyjak-pointing-45631/',30000)
  assert.ok(settings().crosshairConfig.imageData.startsWith('data:image/png;base64,'),'Large static originals are compacted')
  assert.equal(settings().crosshairConfig.imageSize,192)
  await click('[data-library-crosshair$="/donk-white-cs2-xhair/"]')
  await until(()=>settings().crosshairConfig?.imageSource===origin+'/crosshairs/donk-white-cs2-xhair/',30000)
  assert.ok(settings().crosshairConfig.imageData.startsWith('data:image/webp;base64,'))
  await click('[data-library-crosshair$="/rainbow-53038/"]')
  await until(()=>settings().crosshairConfig?.imageSource===origin+'/crosshairs/rainbow-53038/',30000)
  await click('[data-library-crosshair$="/blue-void-41051/"]')
  await until(()=>settings().crosshairConfig?.imageSource===origin+'/crosshairs/blue-void-41051/',30000)
  const data=settings().crosshairConfig.imageData
  assert.ok(data.length>180000,'Larger real animation must survive the old 128 KB limit')
  assert.ok(Buffer.from(data.split(',')[1],'base64').includes(Buffer.from('ANIM')),'Original animation must not be flattened')
