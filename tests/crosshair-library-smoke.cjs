  assert.equal(settings().crosshairConfig.imageData,data,'Browsing categories must preserve selected reticle')
  for(const width of [540,400]){window.setSize(width,920);await new Promise(resolve=>setTimeout(resolve,180));assert.ok(await evaluate('document.documentElement.scrollWidth<=innerWidth+1'))}
