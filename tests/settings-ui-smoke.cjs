    await evaluate(`document.querySelector('[aria-label="Check and save address"]').click();true`)
    await until('document.querySelector("[role=alert]")?.textContent.includes("previous source")')
    assert.equal(await evaluate('document.querySelectorAll(".settings-source-location input")[1].value'), 'https://example.com/new.json')
