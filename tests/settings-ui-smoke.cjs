    assert.equal(await evaluate('document.querySelectorAll("[role=alert]").length'), 0)
    await capture('source-repairs-after')
    window.setSize(620, 940); await wait(120)
    assert.ok(await evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
    await capture('source-repairs-narrow')
    assert.deepEqual(errors, [])
    console.log('Source repair UI passed: verified suggestion, URL validation, failed replacement preserved, manual replacement, alternative switch, keyboard focus, narrow layout')
    window.destroy(); app.exit(0); return
