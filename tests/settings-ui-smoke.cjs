    const content=document.querySelector('.settings-clips-embedded .clip-settings-content'),nav=document.querySelector('.settings-clips-embedded .clip-settings-nav'),heading=document.querySelector('.settings-page-heading'),outer=document.querySelector('.settings-scroll');
