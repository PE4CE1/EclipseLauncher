  assert.equal(await evaluate('document.querySelectorAll(".settings-nav-group button").length'), 11)
  assert.equal(await evaluate('!!document.querySelector("#settings-home-classic,#settings-home-modern")'),false)
  const first = '.settings-option-row input'
  const before = await evaluate(`document.querySelector('${first}').checked`)
  await evaluate(`document.querySelector('${first}').focus();true`)
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Space' })
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Space' })
  await until(`document.querySelector('${first}').checked===${!before}`)
  assert.ok(await evaluate('window.__settingsFixture.writes.length>0'))
  await capture('general-en')
  const tabs = ['downloads','storage','notifications','gameplay','clips','integrations','system','profile','plugins','addons']
