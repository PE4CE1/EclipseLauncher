    await evaluate(`document.querySelector(${JSON.stringify(clipsStartup)}).click();true`)
    await until('window.__settingsFixture.settings().launchInClips===true&&window.__settingsFixture.settings().launchInLibrary===false')
    await evaluate(`document.querySelector(${JSON.stringify(libraryStartup)}).click();true`)
    await until('window.__settingsFixture.settings().launchInLibrary===true&&window.__settingsFixture.settings().launchInClips===false')
    await evaluate(`window.__settingsFixture.failNext();document.querySelector(${JSON.stringify(clipsStartup)}).click();true`)
    await until('window.__settingsFixture.settings().launchInLibrary===true&&window.__settingsFixture.settings().launchInClips===false')
    await evaluate(`document.querySelector(${JSON.stringify(clipsStartup)}).click();true`)
    await until('window.__settingsFixture.settings().launchInClips===true&&window.__settingsFixture.settings().launchInLibrary===false')
    await evaluate('window.__settingsFixture.language("de");true')
    assert.ok(await evaluate('!!document.querySelector(\'[aria-label="Eclipse direkt im Clips Studio starten"]\')'))
    await evaluate('window.__settingsFixture.language("en");true')
