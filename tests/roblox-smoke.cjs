const { app, BrowserWindow, session } = require('electron')
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const output = path.resolve('.cache/roblox'), errors = [], wait = ms => new Promise(resolve => setTimeout(resolve, ms))
app.setPath('userData', process.env.ECLIPSE_SMOKE_TEMP); app.setPath('sessionData', process.env.ECLIPSE_SMOKE_TEMP)
let window
app.whenReady().then(async () => {
  session.defaultSession.protocol.handle('https', () => new Response('<svg xmlns="http://www.w3.org/2000/svg" width="150" height="150"><rect width="150" height="150" fill="#28252a"/><path d="M0 120L90 25L150 120" fill="#9b653f"/><circle cx="40" cy="35" r="14" fill="#e1b982"/></svg>', { headers: { 'content-type': 'image/svg+xml' } }))
  window = new BrowserWindow({ width: 1160, height: 930, show: false, webPreferences: { offscreen: true, sandbox: true, nodeIntegration: false, contextIsolation: true, backgroundThrottling: false } })
  window.webContents.setFrameRate(30)
  window.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message) })
  await window.loadFile(path.join(output, 'fixture/tests/roblox-fixture.html'))
  const evaluate = code => window.webContents.executeJavaScript(code, true)
  const until = async code => { const deadline = Date.now() + 8000; while (Date.now() < deadline) { if (await evaluate(code)) return; await wait(30) } throw Error('Roblox UI timeout: ' + code) }
  const click = selector => evaluate(`document.querySelector(${JSON.stringify(selector)}).click();true`)
  await until('document.querySelectorAll(".rbx-code:not([data-expired]) [data-code-copy]").length===8')
  assert.equal(await evaluate('document.querySelector("[data-code-load-more]").textContent.includes("Load more")'), true)
  const cardHeight = await evaluate('document.querySelector(".rbx-code").getBoundingClientRect().height')
  assert.ok(cardHeight < 125, 'Code cards should be compact')
  await click('[data-code-load-more]')
  await until('document.querySelectorAll("#rbx-active-codes [data-code-copy]").length===16')
  await click('[data-code-load-more]')
  await until('document.querySelectorAll("#rbx-active-codes [data-code-copy]").length===24')
  assert.equal(await evaluate('!!document.querySelector("[data-code-load-more]")'), false)
  await click('.rbx-expired summary')
  assert.equal(await evaluate('document.querySelectorAll("#rbx-expired-codes [data-code-copy]").length'), 8)
  await click('[data-expired-load-more]')
  await until('document.querySelectorAll("#rbx-expired-codes [data-code-copy]").length===16')
  await click('[data-expired-load-more]')
  await until('document.querySelectorAll("#rbx-expired-codes [data-code-copy]").length===21')
  assert.equal(await evaluate('!!document.querySelector("[data-expired-load-more]")'), false)
  await click('.rbx-expired summary')
  await click('[data-code-copy="EASTEREXP"]')
  await until('window.__robloxFixture.copied.at(-1)==="EASTEREXP"')
  await click('[data-code-used="EASTEREXP"]')
  assert.equal(await evaluate('document.querySelector("[data-code-used=EASTEREXP]").getAttribute("aria-pressed")'), 'true')
  await click('[data-code-copy-all]')
  await until('window.__robloxFixture.copied.at(-1).includes("KITT_RESET")')
  assert.equal(await evaluate('window.__robloxFixture.copied.at(-1).split("\\n").length'), 24)
  await evaluate('window.__robloxFixture.select("Rivals");true')
  await until('window.__robloxFixture.calls.includes("Rivals")')
  await evaluate('window.__robloxFixture.select("Fisch");true')
  await until('!!document.querySelector("[data-code-copy=FISCH_FIXTURE]")')
  await evaluate('window.__robloxFixture.finishRivals();window.__robloxFixture.publishRivals();true')
  await wait(100)
  assert.equal(await evaluate('document.querySelector("[data-code-game-title]").textContent'), 'Fisch')
  assert.equal(await evaluate('!!document.querySelector("[data-code-copy=FISCH_FIXTURE]")'), true, 'A late response for another game must never replace current codes')
  await evaluate('window.__robloxFixture.live();true')
  await wait(80)
  assert.equal(await evaluate('document.querySelector("[data-code-game-title]").textContent'), 'Fisch', 'Live detection must respect manual selection')
  await click('.rbx-live')
  await until('document.querySelector("[data-code-game-title]").textContent==="Blox Fruits"')
  assert.equal(await evaluate('document.querySelectorAll("#rbx-active-codes [data-code-copy]").length'), 8, 'Game selection resets pagination')
  assert.equal(await evaluate('document.querySelector("[data-code-used=EASTEREXP]").getAttribute("aria-pressed")'), 'true', 'Used codes survive switching games')
  await evaluate('window.__robloxFixture.language("de");true')
  await until('document.querySelector("[data-roblox-codes] h2").textContent==="Spielcodes"')
  await evaluate('window.__robloxFixture.language("en");true')
  await until('document.querySelector("[data-roblox-codes] h2").textContent==="Game codes"')
  await evaluate('(()=>{const input=document.querySelector("[data-code-search]");input.focus();Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,"value").set.call(input,"Crystal Forest 2");input.dispatchEvent(new Event("input",{bubbles:true}));})()')
  await until('document.querySelector("[role=option]")?.textContent.includes("Crystal Forest 2")')
  await evaluate('document.querySelector("[data-code-search]").dispatchEvent(new KeyboardEvent("keydown",{key:"Enter",bubbles:true}));true')
  await until('document.querySelector("[data-code-game-title]").textContent==="Crystal Forest 2"')
  await until('!!document.querySelector("[data-code-copy=OTHER_FIXTURE]")')
  await evaluate('window.__robloxFixture.select("Blox Fruits");true')
  await until('!!document.querySelector("[data-code-copy=EASTEREXP]")')
  assert.equal(await evaluate('[...document.querySelectorAll(".rbx-code-top code")].some(node=>node.textContent==="FREEGEMS")'), false)
  assert.deepEqual(errors, [])
  for (let attempt = 0; attempt < 5; attempt++) {
    try { window.webContents.invalidate(); await wait(300); fs.writeFileSync(path.join(output, 'roblox-preview.png'), (await window.webContents.capturePage()).toPNG()); break }
    catch (error) { if (attempt === 4 || !/UnknownVizError/.test(String(error))) throw error }
  }
  const report = { copyingWithBrowserClipboardDenied: true, copyAll: true, compactCardHeight: cardHeight, activePagination: '8 → 16 → 24', expiredPagination: '8 → 16 → 21', paginationResetsForGame: true, usedCodesPersist: true, lateResponsesIgnored: true, liveSelectionRespectsUser: true, searchableNonSeededGames: true, keyboardSelection: true, localized: true, rendererErrors: errors }
  fs.writeFileSync(path.join(output, 'ui-verification.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report)); window.destroy(); app.exit(0)
}).catch(async error => { console.error(error); if (window && !window.isDestroyed()) { fs.writeFileSync(path.join(output, 'failure.txt'), await window.webContents.executeJavaScript('document.body.innerText').catch(() => '')); window.destroy() } app.exit(1) })
setTimeout(() => app.exit(1), 30000).unref()
