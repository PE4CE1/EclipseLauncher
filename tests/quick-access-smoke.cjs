const assert=require('node:assert/strict')
module.exports=async({window,evaluate,until,click,capture,settings,failSave,errors})=>{
  const mode=process.env.ECLIPSE_QUICK_ACCESS_MODE==='clips'?'clips':'launcher'
  const ids=()=>evaluate('[...document.querySelectorAll("[data-quick-location=sidebar] [data-quick-action]")].map(button=>button.dataset.quickAction)')
  const choose=async id=>{await evaluate(`document.querySelector('[data-quick-choice=${id}]').scrollIntoView({block:'nearest',behavior:'instant'});true`);await click(`[data-quick-choice=${id}]`)}
  await until(()=>evaluate('!!window.__overlaySettings&&document.querySelectorAll("[data-quick-action]").length===3'))
  assert.ok(await evaluate(`(()=>{const nodes=[...document.querySelectorAll('.overlay-settings-game-list button div')],reference=nodes.find(node=>node.childElementCount===0&&node.textContent.trim()==='Rocket League'),status=reference.parentElement.children[1],fields=['fontFamily','fontSize','fontWeight','lineHeight','color'],same=(a,b)=>fields.every(field=>getComputedStyle(a)[field]===getComputedStyle(b)[field]);return [...document.querySelectorAll('.game-crosshair-title')].slice(0,3).every(title=>same(title.querySelector('strong'),reference)&&same(title.querySelector('small'),status))})()`),'All game headings and status rows use the same typography')
  assert.deepEqual(await ids(),['empty','empty','empty'])
  assert.ok(await evaluate('(()=>{const r=document.querySelector("[data-quick-action]").getBoundingClientRect();return r.width<=34&&r.height<=28})()'))
  await click('[data-quick-slot="0"]')
  await until(()=>evaluate('!!document.querySelector(".quick-access-dialog")'))
  await choose(mode==='clips'?'microphone':'crosshair')
  await click('.quick-access-slots button:nth-child(2)')
  await choose(mode==='clips'?'clip-settings':'performance')
  await click('.quick-access-slots button:nth-child(3)')
  await choose('save-clip')
  await click('[data-dialog-close]')
  assert.equal(await evaluate('document.querySelector("[data-quick-action=save-clip]").disabled'),true)
  assert.ok(await evaluate('document.querySelector(".quick-access").getBoundingClientRect().top>=document.querySelector("[data-test-profile]").getBoundingClientRect().bottom'))
  if(mode==='launcher'){
    await click('[data-quick-action=crosshair]')
    await until(()=>settings().overlayCrosshair===true)
    assert.equal(await evaluate('document.querySelector("[data-quick-action=crosshair]").getAttribute("aria-pressed")'),'true')
    await until(()=>evaluate('getComputedStyle(document.querySelector("[data-quick-action=crosshair]")).color==="rgb(227, 164, 109)"'))
  }else{
    await click('[data-quick-action=microphone]')
    await until(()=>evaluate('window.__overlaySettings.quickState().mic===false'))
  }
  await capture(`quick-access-${mode}.png`)
  await click('[data-quick-edit]')
  await until(()=>evaluate('!!document.querySelector(".quick-access-dialog")'))
  if(mode==='clips')assert.equal(await evaluate('!!document.querySelector("[data-quick-choice=performance]")'),false)
  await choose('friends')
  await until(()=>settings().quickAccess?.[mode]?.[0]==='friends')
  await click('.quick-access-slots button:nth-child(2)')
  await choose('friends')
  await until(()=>settings().quickAccess?.[mode]?.[1]==='friends')
  assert.equal(new Set(await ids()).size,3,'Choosing an existing feature swaps the occupied slots')
  const before=await ids()
  failSave()
  await choose('settings')
  await until(()=>evaluate('document.querySelector("[data-quick-choice=settings]").disabled===false'))
  assert.deepEqual(await ids(),before,'Failed settings writes restore the previous assignment')
  await choose('clip-settings')
  await until(()=>settings().quickAccess[mode][1]==='clip-settings')
  await capture(`quick-access-editor-${mode}.png`)
  await window.webContents.debugger.sendCommand('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
  await window.webContents.debugger.sendCommand('Input.dispatchKeyEvent',{type:'keyUp',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
  await until(()=>evaluate('!document.querySelector(".quick-access-dialog")'))
  assert.equal(await evaluate('document.activeElement.hasAttribute("data-quick-edit")'),true)
  await click('[data-quick-action=clip-settings]')
  await until(()=>evaluate('window.__overlaySettings.quickState().view==="clips"&&window.__overlaySettings.quickState().clipSettings'))
  const saved=await ids(),loaded=new Promise(resolve=>window.webContents.once('did-finish-load',resolve))
  window.webContents.reload();await loaded
  await until(()=>evaluate('!!window.__overlaySettings&&document.querySelectorAll("[data-quick-action]").length===3'))
  assert.deepEqual(await ids(),saved,'Custom slots survive a renderer reload')
  await click('[data-quick-edit]')
  await evaluate('(()=>{const input=document.querySelector(".quick-access-search input");const setter=Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,"value").set;setter.call(input,"zzzz-none");input.dispatchEvent(new Event("input",{bubbles:true}));return true})()')
  await until(()=>evaluate('document.querySelectorAll("[data-quick-choice]").length===0'))
  await window.webContents.debugger.sendCommand('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
  await until(()=>evaluate('!document.querySelector(".quick-access-dialog")'))
  for(const location of ['topbar','titlebar'])await click(`[data-quick-location-setting=${location}] [role=switch]`)
  await until(()=>evaluate('document.querySelectorAll(".quick-access").length===3'))
  assert.ok(await evaluate('getComputedStyle(document.querySelector("[data-quick-location=titlebar]")).webkitAppRegion==="no-drag"'))
  await capture(`quick-access-locations-${mode}.png`)
  await click('[data-quick-location=titlebar] [data-quick-edit]')
  await click('[data-quick-clear]')
  await until(()=>evaluate('[...document.querySelectorAll(".quick-access")].every(row=>row.querySelector("[data-quick-slot]").dataset.quickAction==="empty")'))
  window.setSize(760,620)
  await new Promise(resolve=>setTimeout(resolve,160))
  assert.ok(await evaluate('(()=>{const r=document.querySelector(".quick-access-dialog").getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight})()'),'Title-bar editor stays within a resized window')
  await click('[data-dialog-close]')
  await click('[data-quick-location-setting=sidebar] [role=switch]')
  await until(()=>evaluate('!document.querySelector("[data-quick-location=sidebar]")'))
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({mode,threeSlots:true,toggles:true,swaps:true,failureRollback:true,persisted:true,navigation:true,keyboardDismiss:true,modeFiltering:true}))
}
