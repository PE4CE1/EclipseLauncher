const assert=require('node:assert/strict'),wait=ms=>new Promise(resolve=>setTimeout(resolve,ms))
module.exports=async({window,evaluate,capture,click,change,until})=>{
  const tap=async selector=>{
    await evaluate(`document.querySelector(${JSON.stringify(selector)}).scrollIntoView({block:'center',behavior:'instant'});true`)
    window.webContents.invalidate();await window.webContents.capturePage();await wait(80);await click(selector)
  }
  await evaluate(`(()=>{const meta=document.createElement('meta');meta.httpEquiv='Content-Security-Policy';meta.content="script-src 'self'; worker-src 'self' blob:";document.head.append(meta);window.__clipFixture.microphonePermission(true);return true})()`)
  await tap('#clips-open-settings');await tap('#clip-settings-tab-audio')
  await until('document.querySelector("#clip-setting-mic-device option[value=fixture-mic]")?.textContent==="Fixture microphone"')
  assert.equal(await evaluate('window.__clipFixture.state().deviceRequests.microphone'),1,'Hidden names require one short microphone permission stream')
  await until('window.__clipFixture.state().liveTracks===0')
  assert.equal(await evaluate('document.querySelectorAll("#clip-setting-mic-device option").length'),2)
  await change('#clip-setting-mic-device','fixture-mic')
  await tap('.clip-settings-mic-test button')
  await until('Number(document.querySelector("[role=meter]").getAttribute("aria-valuenow"))>-30')
  await until('document.querySelector(".clip-mic-gate").dataset.gateOpen==="true"')
  await evaluate('document.querySelector(".clip-mic-gate").scrollIntoView({block:"center"});true')
  await capture('microphone-passing-de.png')
  await change('#clip-setting-noise-gate','-10')
  await until('document.querySelector(".clip-mic-gate").dataset.gateOpen==="false"')
  assert.ok(await evaluate('Number(document.querySelector("[role=meter]").getAttribute("aria-valuenow"))>-30'),'A closed gate must still show raw input')
  await capture('microphone-gated-de.png')
  await change('#clip-setting-noise-gate','-35')
  await until('document.querySelector(".clip-mic-gate").dataset.gateOpen==="true"')
  assert.equal(await evaluate('window.__clipFixture.state().deviceRequests.microphone'),2,'Threshold changes must not reopen the microphone')
  await evaluate('window.__clipFixture.microphoneLevel(.001);true')
  await until('document.querySelector(".clip-mic-gate").dataset.gateOpen==="false"')
  await change('#clip-setting-noise-gate','-60')
  await until('document.querySelector(".clip-mic-gate").dataset.gateOpen==="true"')
  await tap('.clip-settings-mic-test button');await until('window.__clipFixture.state().liveTracks===0')
  await evaluate(`window.__clipFixture.devices([{kind:'audioinput',deviceId:'default',label:'Default - USB Headset'},{kind:'audioinput',deviceId:'usb-headset',label:'USB Headset'}]);true`)
  await until('!!document.querySelector("#clip-setting-mic-device option[value=usb-headset]")')
  assert.match(await evaluate('document.querySelector("#clip-setting-mic-device option[value=auto]").textContent'),/USB Headset/)
  assert.match(await evaluate('document.querySelector("#clip-setting-mic-device option[value=fixture-mic]").textContent'),/nicht verfügbar/)
  await change('#clip-setting-mic-device','usb-headset')
  for(const width of [1120,540,400]){
    window.setSize(width,840);await wait(120)
    assert.ok(await evaluate('(()=>{const root=document.querySelector(".clip-settings-content");return root.scrollWidth<=root.clientWidth+1})()'),'Noise gate must fit '+width)
    await capture('microphone-'+width+'.png')
  }
  window.setSize(1120,840)
  await evaluate('window.__clipFixture.language("en");window.__clipFixture.microphonePermission(true,true);true')
  await tap('.clip-settings-page-heading button')
  await until('[...document.querySelectorAll("[role=alert]")].some(node=>node.textContent.includes("Windows microphone privacy"))')
  await tap('.clip-settings-mic-test button')
  await until('!!document.querySelector(".clip-mic-gate-error")')
  assert.match(await evaluate('document.querySelector(".clip-mic-gate-error").textContent'),/access is blocked/)
  await capture('microphone-permission-en.png')
  await evaluate('window.__clipFixture.microphonePermission(false);true')
  await tap('.clip-settings-page-heading button')
  await until('!document.querySelector(".clip-settings-note[role=alert]")')
  await tap('.clip-settings-mic-test button');await until('window.__clipFixture.state().liveTracks>0')
  await tap('#clip-settings-tab-video');await until('window.__clipFixture.state().liveTracks===0')
  return{permissionNames:true,gateOpensAndCloses:true,rawInputVisibleWhileMuted:true,thresholdLive:true,offBypass:true,hotplug:true,disconnectedSelection:true,localizedErrors:true,unmountCleanup:true}
}
