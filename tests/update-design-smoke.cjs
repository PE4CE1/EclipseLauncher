const { app, BrowserWindow, session } = require('electron')
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const output = path.join(__dirname, '../.cache/update-design'), wait = ms => new Promise(resolve => setTimeout(resolve, ms))
app.setPath('userData', process.env.ECLIPSE_SMOKE_TEMP); app.setPath('sessionData', process.env.ECLIPSE_SMOKE_TEMP)
app.whenReady().then(async () => {
  fs.mkdirSync(output, { recursive: true })
  session.defaultSession.webRequest.onBeforeRequest((details, done) => done({ cancel: /^https?:/.test(details.url) }))
  const window = new BrowserWindow({ show: false, width: 1180, height: 900, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } })
  const errors = []
  window.webContents.on('console-message', event => { if (event.level === 'error' && !/ERR_|Failed to load resource/.test(event.message)) errors.push(event.message) })
  const evaluate = code => window.webContents.executeJavaScript(code, true).catch(error => { throw new Error(`${error.message}: ${code}`) })
  const until = async code => { const end = Date.now() + 7000; while (Date.now() < end) { if (await evaluate(code)) return; await wait(30) } throw new Error('Update UI timeout: ' + code) }
  const capture = async name => {
    await wait(350)
    let image
    for (let i = 0; i < 8; i++) { window.webContents.invalidate(); image = await window.webContents.capturePage(); await wait(50) }
    fs.writeFileSync(path.join(output, name + '.png'), image.toPNG())
  }
  await window.loadFile(path.join(output, 'fixture/tests/update-design-fixture.html'))
  await until('window.__updateFixture?.ready()')
  await evaluate('window.__updateFixture.emit("available",window.__updateFixture.release);true')
  await until('document.querySelector(".eclipse-update")?.dataset.updateState==="available"')
  await evaluate('document.fonts.ready.then(()=>true)')
  await capture('update-available-de')
  const availableButtonTop = await evaluate('document.querySelector(".eclipse-update__primary").getBoundingClientRect().top')
  assert.equal(await evaluate('document.querySelector(".eclipse-update__version").textContent'), '2.1.0')
  await evaluate('document.querySelector(".eclipse-update__primary").click();document.querySelector(".eclipse-update__primary").click();true')
  await until('document.querySelector(".eclipse-update")?.dataset.updateState==="downloading"')
  assert.equal(await evaluate('window.__updateFixture.calls.downloads'), 1)
  assert.equal(await evaluate('document.querySelector("[role=progressbar]").getAttribute("aria-valuenow")'), '0')
  await evaluate('window.__updateFixture.emit("downloading",{percent:49.9});true')
  await until('document.querySelector("[role=progressbar]").getAttribute("aria-valuenow")==="49"')
  assert.ok(Math.abs(await evaluate('document.querySelector(".eclipse-update__primary").getBoundingClientRect().top') - availableButtonTop) < 1, 'Starting the download must not move its button')
  await capture('update-downloading-de')
  await evaluate('window.__updateFixture.emit("downloaded",{filePath:"test-only.exe"});true')
  await until('document.querySelector(".eclipse-update")?.dataset.updateState==="downloaded"')
  await capture('update-ready-de')
  await evaluate('document.querySelector(".eclipse-update__primary").click();true')
  await until('window.__updateFixture.calls.installs===1')
  await evaluate('window.__updateFixture.mode("notifications");true')
  await until('!document.querySelector(".launch-screen")&&!!document.querySelector(".eclipse-update")')
  assert.equal(await evaluate('document.querySelector(".eclipse-update__version").textContent'), '2.1.0', 'Downloaded file events must not erase the version')
  await evaluate('window.__updateFixture.emit("error","Connection interrupted");true')
  await until('!!document.querySelector(".eclipse-update [role=alert]")')
  await capture('update-error-de')
  await evaluate('document.querySelector(".eclipse-update__primary").click();true')
  await until('window.__updateFixture.calls.downloads===2')
  await evaluate('window.__updateFixture.emit("available",window.__updateFixture.release);window.__updateFixture.language("en");true')
  await until('document.querySelector(".eclipse-update__primary").textContent.includes("Download update")')
  await capture('update-available-en')
  await evaluate('document.querySelector(".eclipse-update__release-link").click();true')
  assert.equal(await evaluate('window.__updateFixture.calls.links.at(-1)'), 'https://github.com/PE4CE1/EclipseLauncher/releases/latest')
  for (const width of [620, 400, 320]) {
    window.setSize(width, 900); await wait(150)
    assert.ok(await evaluate('document.querySelector(".eclipse-update").scrollWidth<=document.querySelector(".eclipse-update").clientWidth+1'), 'Update card overflow at ' + width)
    await capture('update-narrow-' + width)
  }
  assert.deepEqual(errors, [])
  fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify({ states: ['available', 'downloading', 'downloaded', 'error'], realComponents: ['SplashView', 'NotificationsView'], duplicateClickGuard: true, zeroProgress: true, versionPreserved: true, retry: true, languages: ['de', 'en'], widths: [1180, 620, 400, 320], rendererErrors: errors }, null, 2))
  console.log('Update UI verified: startup and notification states, download/restart actions, error retry, version retention, DE/EN, narrow cards')
  window.destroy(); app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
setTimeout(() => { console.error('Update UI smoke timeout'); app.exit(1) }, 60000).unref()
