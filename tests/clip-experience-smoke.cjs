const { app, BrowserWindow, ipcMain, session } = require('electron')
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..'), output = path.join(root, '.cache/clip-experience')
app.setPath('userData', process.env.ECLIPSE_SMOKE_TEMP); app.setPath('sessionData', process.env.ECLIPSE_SMOKE_TEMP)
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
let window, game = { name: 'VALORANT', exeName: 'valorant.exe', pid: 222 }, applications = [{ name: 'valorant.exe', pid: 222 }, { name: 'Discord.exe', pid: 333 }], requests = 0
const errors = []
app.whenReady().then(async () => {
  fs.mkdirSync(output, { recursive: true })
  ipcMain.on('account:get-identity-sync', event => { event.returnValue = null })
  ipcMain.handle('settings:set', () => ({ success: true }))
  ipcMain.handle('clips:audio-processes', () => { requests++; return { supported: true, processes: applications, detectedGame: game } })
  session.defaultSession.webRequest.onBeforeRequest((details, callback) => callback({ cancel: /^https?:/.test(details.url) }))
  window = new BrowserWindow({ show: false, frame: false, width: 1120, height: 840, webPreferences: { preload: path.join(root, 'dist-electron/preload.js'), sandbox: true, contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } })
  window.webContents.on('console-message', event => { if (event.level === 'error' && !/ERR_|Failed to load resource|404/.test(event.message)) errors.push(event.message) })
  await window.loadFile(path.join(root, '.cache/clip-studio/fixture/tests/clip-studio-fixture.html'), { query: { experience: '1' } })
  const evaluate = code => window.webContents.executeJavaScript(code, true)
  const until = async (code, timeout = 4000) => { const end = Date.now() + timeout; while (Date.now() < end) { if (await evaluate(code)) return; await wait(40) } throw Error('Experience fixture timeout: ' + code) }
  const capture = async name => {
    for (let frame = 0; frame < 14; frame++) { window.webContents.invalidate(); await window.webContents.capturePage(); await wait(55) }
    fs.writeFileSync(path.join(output, name), (await window.webContents.capturePage()).toPNG())
  }
  window.webContents.debugger.attach('1.3')
  await until('!!window.__clipExperience && document.querySelector("#clip-setting-game-process")?.value === "auto"')
  await until('window.__clipExperience.settings().gameAudioProcess === "auto"')
  await evaluate('Promise.all([document.fonts.ready,...[...document.images].map(image=>image.decode().catch(()=>{}))]).then(()=>true)')
  assert.match(await evaluate('document.querySelector("#clip-setting-game-process option:checked").textContent'), /Automatic.*VALORANT/)
  assert.doesNotMatch(await evaluate('document.querySelector("#clip-setting-game-process").textContent'), /RocketLeague|Discord/)
  await capture('audio-auto-valorant.png')
  game = { name: 'Overwatch', exeName: 'Overwatch.exe', pid: 444 }; applications = [{ name: 'Overwatch.exe', pid: 444 }]
  window.webContents.send('games:started', { name: 'Overwatch', startTime: Date.now() })
  await until('document.querySelector("#clip-setting-game-process option:checked").textContent.includes("Overwatch")')
  game = null; applications = []
  window.webContents.send('games:stopped')
  await until('document.querySelector("#clip-setting-game-process option:checked").textContent.includes("Waiting for a game")')
  await capture('audio-auto-waiting.png')
  const idle = await evaluate('(()=>{const s=getComputedStyle(document.querySelector("[data-eclipse-trigger]"));return{shadow:s.boxShadow,filter:s.filter,transform:s.transform}})()')
  assert.equal(idle.shadow, 'none'); assert.equal(idle.filter, 'none')
  const point = await evaluate('(()=>{const r=document.querySelector("[data-eclipse-trigger]").getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}})()')
  await window.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mouseMoved', ...point })
  await wait(150)
  assert.equal(await evaluate('getComputedStyle(document.querySelector("[data-eclipse-trigger]")).boxShadow'), 'none')
  assert.equal(await evaluate('getComputedStyle(document.querySelector("[data-eclipse-trigger]")).transform'), idle.transform)
  await evaluate('document.querySelector("[data-eclipse-trigger]").click();true')
  await until('!!document.querySelector("[data-eclipse-cinema]")')
  assert.equal(await evaluate('document.querySelectorAll("[data-eclipse-cinema]").length'), 1)
  await wait(750)
  await capture('eclipse-countdown.png')
  assert.ok(Number(await evaluate('getComputedStyle(document.querySelector("[data-eclipse-cinema]")).opacity')) > .99)
  assert.equal(await evaluate('document.querySelector("[data-eclipse-trigger]").getAttribute("aria-expanded")'), 'true')
  assert.notEqual(await evaluate('getComputedStyle(document.querySelector("[data-eclipse-trigger]")).boxShadow'), 'none')
  assert.equal(await evaluate('!!document.querySelector(".eclipse-cinema-moon")'), false)
  assert.match(await evaluate('document.querySelector(".eclipse-countdown-number").textContent'), /years/)
  assert.match(await evaluate('document.querySelector(".eclipse-countdown-event time").dateTime'), /^20\d{2}-\d{2}-\d{2}$/)
  await evaluate('window.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}));true')
  assert.equal(await evaluate('!!document.querySelector("[data-eclipse-cinema]")'), true, 'Keep the modal mounted through its exit fade')
  await until('!document.querySelector("[data-eclipse-cinema]")')
  await window.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  await wait(100)
  await evaluate('document.querySelector("[data-eclipse-trigger]").click();true')
  await until('document.querySelector("[data-eclipse-cinema]")?.dataset.motion === "reduced"')
  await capture('eclipse-countdown-reduced.png')
  await evaluate('document.querySelector(".eclipse-countdown-close").click();true')
  await until('!document.querySelector("[data-eclipse-cinema]")')
  assert.deepEqual(errors, [])
  const result = { staleSelectionMigrated: true, liveGameChanges: true, waitsWithoutGame: true, idleLogoEffects: idle, singleClickResponsive: true, countdownInsteadOfCinema: true, glowOnlyWhenOpen: true, exitFade: true, reducedMotion: true, requests, errors }
  fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify(result, null, 2)); console.log(JSON.stringify(result, null, 2))
  window.destroy(); app.exit(0)
}).catch(error => { console.error(error); if (window && !window.isDestroyed()) window.destroy(); app.exit(1) })
