const test=require('node:test'),assert=require('node:assert/strict'),load=require('./download-loader.cjs')
const {createCS2Session}=load()('electron/cs2Stats.ts')
const packet=(kills,deaths=0,round=0,hs=0,time=1)=>({provider:{appid:730,steamid:'76561198000000000',timestamp:time},player:{steamid:'76561198000000000',activity:'playing',match_stats:{kills,deaths,assists:0},state:{round_kills:kills,round_killhs:hs}},map:{phase:'live',name:'de_dust2',mode:'competitive',round,team_ct:{score:4},team_t:{score:3}}})
test('CS2 session counts only local player deltas, deduplicates packets and retains totals across matches',()=>{
  const session=createCS2Session()
  assert.equal(session.ingest(packet(10,3)).kills,0)
  const next=packet(12,4,0,1,2),stats=session.ingest(next)
  assert.equal(stats.kills,2);assert.equal(stats.deaths,1);assert.equal(stats.headshots,1);assert.equal(stats.headshotKills,2)
  assert.equal(session.ingest(next).kills,2)
  assert.equal(session.ingest(packet(11,3,0,0,1)),undefined)
  session.disconnect();assert.equal(session.read().lastSeenAt,0)
  session.ingest(packet(0));assert.equal(session.ingest(packet(1,1,0,1,3)).kills,3)
  assert.equal(session.read().ct,4);session.reset();assert.equal(session.read().kills,0)
})
test('CS2 session rejects other apps, spectator statistics and malformed counters',()=>{
  const session=createCS2Session(),wrong=packet(1)
  wrong.player.steamid='76561198000000001';assert.equal(session.ingest(wrong),undefined)
  const bad=packet(-1);assert.equal(session.ingest(bad),undefined)
  const app=packet(1);app.provider.appid=570;assert.equal(session.ingest(app),undefined)
  assert.equal(session.read().kills,0)
})
