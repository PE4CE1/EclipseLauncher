const assert = require('node:assert/strict')
module.exports = async ({ evaluate, until, click, change, key, capture, calls }) => {
  const input = '[data-clip-rename-input="gallery-0"]'
  const title = '[data-clip-card="gallery-0"] .clip-library-title'
  await click('[data-clip-rename="gallery-0"]')
  await until(`document.activeElement===document.querySelector('${input}')`)
  assert.equal(await evaluate(`document.querySelector('${input}').selectionEnd`), 'Gameplay Highlight'.length)
  assert.equal(await evaluate('!!document.querySelector("[data-clip-editor]")'), false)
  await capture('gallery-quick-rename.png')
  await change(input, '  Mein erster Clip · Sieg  ')
  await key('Enter')
  assert.equal(await evaluate('getComputedStyle(document.querySelector("[data-clip-card=gallery-0] .clip-library-preview")).opacity'), '1', 'Saving a title must not flash or dim the thumbnail')
  await until(`document.querySelector('${title}')?.textContent==='Mein erster Clip · Sieg'`)
  assert.equal(calls.filter(call => call.name === 'rename').length, 1)
  assert.equal(await evaluate('window.electronAPI.clips.listClips().then(clips=>clips.find(clip=>clip.id==="gallery-0").title)'), 'Mein erster Clip · Sieg')
  await click('[data-clip-rename="gallery-0"]')
  await change(input, 'Nicht speichern')
  await key('Escape')
  await until(`!!document.querySelector('${title}')`)
  assert.equal(await evaluate(`document.querySelector('${title}').textContent`), 'Mein erster Clip · Sieg')
  assert.equal(calls.filter(call => call.name === 'rename').length, 1)
  await click('[data-clip-rename="gallery-0"]')
  await change(input, '   ')
  await key('Enter')
  assert.equal(await evaluate(`document.querySelector('${input}').getAttribute('aria-invalid')`), 'true')
  assert.equal(calls.filter(call => call.name === 'rename').length, 1)
  await change(input, 'Save failure')
  await key('Enter')
  await until('!!document.querySelector(".clip-library-rename-error")')
  assert.equal(await evaluate(`document.querySelector('${input}').value`), 'Save failure')
  await change(input, 'Mein Clip · Runde 2')
  await click('[data-clip-rename-save="gallery-0"]')
  await until(`document.querySelector('${title}')?.textContent==='Mein Clip · Runde 2'`)
  await change('.clip-library-search input', 'Runde 2')
  await until('document.querySelectorAll("[data-clip-card]").length===1')
  await change('.clip-library-search input', '')
  await until('document.querySelectorAll("[data-clip-card]").length===151')
  assert.equal(await evaluate(`document.querySelector('${title}').textContent`), 'Mein Clip · Runde 2')
  return { inline: true, save: true, cancel: true, emptyRejected: true, failedSaveRetry: true, searchUpdated: true, retainedAfterRemount: true }
}
