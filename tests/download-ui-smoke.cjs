const { app, BrowserWindow, ipcMain, session } = require('electron')
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const root = path.join(__dirname, '..'), output = path.join(root, '.cache/download-ui')
app.setPath('userData', process.env.ECLIPSE_SMOKE_TEMP)
app.setPath('sessionData', process.env.ECLIPSE_SMOKE_TEMP)
app.on('window-all-closed', () => {})
const deadline = setTimeout(() => { console.error('Download UI smoke timed out'); app.exit(1) }, 35_000)
const wait = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds))
app.whenReady().then(async () => {
  ipcMain.on('account:get-identity-sync', event => { event.returnValue = null })
  ipcMain.handle('settings:set', () => ({ success: true }))
  for (const [name,value] of Object.entries({ 'app:get-default-download-path': 'C:\\Users\\Player\\Downloads', 'dialog:open-directory': 'D:\\Games', 'system:open-url': true, 'http-download:pause': true, 'http-download:resume': true, 'http-download:cancel': true, 'torrent:pause': true, 'torrent:resume': true, 'torrent:cancel': true })) ipcMain.handle(name, () => value)
  ipcMain.handle('link:inspect', (_event,url) => ({ state: url.includes('datanodes') ? 'verification' : url.includes('viking') ? 'unknown' : 'reachable' }))
  session.defaultSession.webRequest.onBeforeRequest((details, callback) => callback({ cancel: /^https?:/.test(details.url) }))
  const window = new BrowserWindow({ show: false, frame: false, width: 1200, height: 870, webPreferences: { preload: path.join(root, 'dist-electron/preload.js'), sandbox: true, contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } })
  const errors = []
  window.webContents.on('console-message', event => { if (event.level === 'error' && !/ERR_|Failed to load resource|404|No handler registered/.test(event.message)) errors.push(event.message) })
  const evaluate = code => window.webContents.executeJavaScript(code, true)
  const until = async code => { const end = Date.now() + 5000; while (Date.now() < end) { if (await evaluate(code)) return; await wait(40) } throw new Error('UI timeout: ' + code) }
  const capture = async name => {
    let image
    for (let frame = 0; frame < 12; frame++) {
      try { window.webContents.invalidate(); image = await window.webContents.capturePage() }
      catch (error) { if (!/UnknownVizError/.test(String(error)) || frame === 11) throw error }
      await wait(45)
    }
    fs.writeFileSync(path.join(output, name), image.toPNG())
  }
  await window.loadFile(path.join(output, 'fixture/tests/download-fixture.html'))
  await until('!!document.querySelector(".download-release")')
  await evaluate('document.fonts.ready.then(()=>true)')
  const height = await evaluate('document.querySelector(".download-dialog-panel").getBoundingClientRect().height')
  assert.ok(height < 440, 'One release must not leave a giant empty dialog')
  await capture('release-list.png')
  await evaluate('document.querySelector(".download-release").click();true')
  await until('document.querySelectorAll(".download-host-status[data-state=reachable]").length>0')
  assert.equal(await evaluate('document.querySelectorAll(".download-host-list input:checked").length'), 1)
  assert.doesNotMatch(await evaluate('document.querySelector(".download-dialog-panel").textContent'), /Highspeed|Online|Offline|Native Installer/)
  assert.equal(await evaluate('[...document.querySelectorAll(".download-host-copy strong")].filter(node=>node.textContent==="DataNodes").length'), 1)
  await evaluate('document.querySelector(".download-preferences input").click();true')
  assert.equal(await evaluate('document.querySelectorAll(".download-preferences input")[1].disabled'), true)
  await evaluate('document.querySelector(".download-preferences input").click();true')
  await capture('download-setup.png')
  await evaluate('document.querySelector(".download-primary").click();true')
  await until('!!window.__downloadRequest')
  assert.match(await evaluate('window.__downloadRequest[0]'), /filekeeper/)
  assert.equal(await evaluate('window.__downloadRequest[6].length'), 6)
  await evaluate('window.__downloadsFixture.error();true')
  await until('!!document.querySelector(".download-task[data-status=error]")')
  assert.doesNotMatch(await evaluate('document.querySelector(".download-error-summary").textContent'), /No automatic mirror|https:|Trying another mirror/)
  assert.match(await evaluate('document.querySelector(".download-workspace-stats").textContent'), /0 active/)
  await capture('download-error.png')
  await evaluate('document.querySelector(".download-detail-toggle").click();true')
  await until('document.querySelectorAll(".download-failure").length===5')
  await capture('host-details.png')
  await evaluate('window.__downloadsFixture.language("de");true')
  await until('document.querySelector(".download-error-summary").textContent.includes("geprüft")')
  await capture('download-error-de.png')
  await evaluate('window.__downloadsFixture.active();true')
  await until('!!document.querySelector(".download-task-progress")')
  await capture('download-active.png')
  window.setSize(850, 650)
  await evaluate('window.__downloadsFixture.open();true')
  await until('!!document.querySelector(".download-release")')
  await evaluate('document.querySelector(".download-release").click();true')
  await until('!!document.querySelector(".download-primary")')
  const bounds = await evaluate('(()=>{const r=document.querySelector(".download-primary").getBoundingClientRect();return{bottom:r.bottom,top:r.top,viewport:innerHeight,overflow:document.documentElement.scrollWidth>innerWidth}})()')
  assert.ok(bounds.top > 0 && bounds.bottom <= bounds.viewport && !bounds.overflow)
  await capture('download-setup-small.png')
  await evaluate('document.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}));true')
  await until('!document.querySelector(".download-dialog-panel")')
  await evaluate('window.__downloadsFixture.many();window.__downloadsFixture.open();true')
  await until('document.querySelectorAll(".download-release").length===12')
  assert.equal(await evaluate('(()=>{const list=document.querySelector(".download-release-list");return list.scrollHeight>list.clientHeight})()'), true)
  await evaluate('(()=>{const input=document.querySelector(".download-dialog-filters input");Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,"value").set.call(input,"v.2.11");input.dispatchEvent(new Event("input",{bubbles:true}));return true})()')
  await until('document.querySelectorAll(".download-release").length===1')
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ success: true, singleReleaseHeight: height, errorGroups: 5, smallWindowFits: true, errors }))
  clearTimeout(deadline); window.destroy(); app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
