const {app,BrowserWindow,session,ipcMain,protocol,net}=require('electron')
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..'),output=path.join(root,'.cache/profile'),wait=ms=>new Promise(resolve=>setTimeout(resolve,ms))
app.setPath('userData',process.env.ECLIPSE_SMOKE_TEMP);app.setPath('sessionData',process.env.ECLIPSE_SMOKE_TEMP)
let window,failSave=false,steamFixture=false;const writes=[],errors=[],links=[],steamReads=[]
app.whenReady().then(async()=>{
  fs.mkdirSync(output,{recursive:true})
  ipcMain.on('account:get-identity-sync',event=>event.returnValue=null)
  ipcMain.handle('sources:get-all-cached',()=>[])
  ipcMain.handle('account:save-identity',()=>({success:true}))
  const {prefetchSteamImage}=require('./download-loader.cjs')({electron:{net}})('electron/artworkPrefetch.ts')
  ipcMain.handle('artwork:prefetch',(_event,request)=>prefetchSteamImage(request.url))
  ipcMain.handle('settings:set',(_event,patch)=>{if(failSave)return{success:false};writes.push(patch);return{success:true}})
  const frameUrl='https://shared.fastly.steamstatic.com/community_assets/images/items/570/c6a479fae8979bc9c1a02378e488e3ce06b52cb1.png'
  const staticFrame='https://shared.fastly.steamstatic.com/community_assets/images/items/570/cbd274867889e08f71c57e42004e2369a991463d.png'
  ipcMain.handle('util:fetch',(_event,url)=>{
    steamReads.push(url)
    if(!steamFixture)return null
    if(url.includes('games/'))return'<profile><games/></profile>'
    if(url.includes('badges/'))return'<html></html>'
    if(url.includes('xml=1'))return'<profile><steamID64>76561198000000000</steamID64><steamID>New profile name</steamID><avatarFull>https://fixture.eclipse/avatar.png</avatarFull><onlineState>online</onlineState></profile>'
    if(steamFixture==='unavailable')return'<html><title>Temporary error</title></html>'
    return `<html><div class="profile_avatar_frame"><img src="https://evil.invalid/comment-frame.png"></div><div class="profile_header"><div class="playerAvatar"><div class="playerAvatarAutoSizeInner">${steamFixture==='none'?'':`<div class="profile_avatar_frame"><picture><source media="(prefers-reduced-motion: reduce)" srcset="${staticFrame}"><img src="${frameUrl}"></picture></div>`}<picture><img src="https://fixture.eclipse/avatar.png"></picture></div></div></div></html>`
  })
  ipcMain.handle('system:open-url',(_event,url)=>{links.push(url);return{success:true}})
  ipcMain.handle('network:request',()=>({status:404,headers:{},body:'',url:'https://fixture.eclipse/missing'}))
  // Only fixture portraits are generated; Steam's own artwork can load without profile/account requests.
  protocol.handle('https',async request=>{
    const url=new URL(request.url)
    if(/steamstatic\.com$/.test(url.hostname)){
      try {return await net.fetch(request.url,{bypassCustomProtocolHandlers:true,signal:AbortSignal.timeout(6000)})} catch{}
    }
    if(url.hostname!=='fixture.eclipse'&&!/steamstatic\.com$/.test(url.hostname))return new Response('',{status:404})
    const color=url.pathname.includes('badge')?'#ba6b43':'#3d4a50'
    return new Response(`<svg xmlns="http://www.w3.org/2000/svg" width="480" height="320"><rect width="480" height="320" fill="${color}"/><circle cx="240" cy="120" r="60" fill="#d2c4ab"/><path d="M80 320Q90 190 240 190Q390 190 400 320" fill="#17191d"/></svg>`,{headers:{'content-type':'image/svg+xml','access-control-allow-origin':'*'}})
  })
  window=new BrowserWindow({show:false,frame:false,width:1400,height:1050,webPreferences:{preload:path.join(root,'dist-electron/preload.js'),sandbox:true,contextIsolation:true,nodeIntegration:false,backgroundThrottling:false}})
  window.webContents.on('console-message',event=>{if(event.level==='error'&&!/ERR_|Failed to load resource/.test(event.message))errors.push(event.message)})
  const evaluate=code=>window.webContents.executeJavaScript(code,true)
  const until=async(code,timeout=12000)=>{const end=Date.now()+timeout;while(Date.now()<end){if(await evaluate(code))return;await wait(30)}throw Error('Profile timeout: '+code)}
  window.webContents.debugger.attach('1.3')
  const click=async selector=>{
    await evaluate(`document.querySelector(${JSON.stringify(selector)}).scrollIntoView({block:'center',behavior:'instant'});true`)
    const point=await evaluate(`(()=>{const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}})()`)
    for(const type of ['mousePressed','mouseReleased'])await window.webContents.debugger.sendCommand('Input.dispatchMouseEvent',{type,...point,button:'left',clickCount:1})
    await wait(60)
  }
  const input=async(selector,value)=>{await evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event('input',{bubbles:true}));})()`);await wait(70)}
  const key=async(key,modifiers=0)=>{for(const type of ['keyDown','keyUp'])await window.webContents.debugger.sendCommand('Input.dispatchKeyEvent',{type,key,code:key,modifiers});await wait(70)}
  const capture=async name=>{for(let i=0;i<3;i++){window.webContents.invalidate();await window.webContents.capturePage();await wait(80)}fs.writeFileSync(path.join(output,name),(await window.webContents.capturePage()).toPNG())}
  await window.loadFile(path.join(root,'.cache/profile/fixture/tests/profile-fixture.html'))
  await until('!!document.querySelector(".profile-name h1")')
  await wait(1800)
  assert.equal(await evaluate('document.querySelector(".profile-name h1").textContent'),'SERGEANTPEACE(GER)')
  assert.equal(await evaluate('document.querySelectorAll(".profile-featured-game").length'),3)
  assert.equal(await evaluate('document.querySelectorAll(".profile-numbers strong")[2].textContent'),'3')
  await capture('profile-overview.png')
  await click('#profile-tab-games')
  await input('.profile-search input','portal')
  assert.equal(await evaluate('document.querySelectorAll(".profile-game-tile").length'),1)
  assert.match(await evaluate('document.querySelector(".profile-game-tile").textContent'),/Portal 2/)
  await input('.profile-search input','')
  await click('.profile-games-section .profile-text-button')
  assert.equal(await evaluate('document.querySelectorAll(".profile-pin-button[aria-pressed=true]").length'),3)
  assert.equal(await evaluate('document.querySelectorAll(".profile-pin-button:disabled").length'),5)
  await click('.profile-pin-button[aria-pressed=true]')
  assert.equal(await evaluate('window.__profileFixture.state().settings.profilePinnedGames.length'),2)
  await input('.profile-search input','Portal')
  await click('.profile-pin-button');await until('window.__profileFixture.state().settings.profilePinnedGames.includes("steam:620")')
  assert.equal(writes.at(-1).profilePinnedGames.length,3)
  await input('.profile-search input','')
  await click('#profile-tab-overview')
  assert.match(await evaluate('document.querySelector(".profile-showcase").textContent'),/Portal 2/)
  await click('.profile-actions .profile-button-primary')
  await until('!!document.querySelector("[role=dialog]")')
  await capture('profile-editor.png')
  await evaluate('document.querySelector(".profile-checkbox input").focus();true')
  await key(' ');assert.equal(await evaluate('document.activeElement===document.querySelector(".profile-checkbox input")'),true,'Checkbox focus survives state changes')
  await key(' ')
  await input('.profile-editor input[aria-label]','New profile name')
  failSave=true;await click('.profile-editor-save')
  await until('!!document.querySelector(".profile-editor [role=alert]")')
  assert.equal(await evaluate('window.__profileFixture.state().settings.username'),'SERGEANTPEACE(GER)')
  failSave=false;await click('.profile-editor-save');await until('!document.querySelector("[role=dialog]")')
  assert.equal(await evaluate('document.querySelector(".profile-name h1").textContent'),'New profile name')
  assert.ok(writes.some(patch=>patch.username==='New profile name'))
  await click('.profile-actions .profile-button-primary')
  await key('Escape');await until('!document.querySelector("[role=dialog]")')
  assert.equal(await evaluate('document.activeElement.classList.contains("profile-button-primary")'),true)
  await evaluate('window.__profileFixture.settings({profileShowPlaytime:false,profileShowSteamStats:false});true')
  await until('document.querySelectorAll(".profile-numbers strong").length===2')
  assert.equal(await evaluate('document.querySelectorAll(".profile-playtime-list,.profile-recent-list,.profile-steam-stats").length'),0)
  assert.equal(await evaluate('!!document.querySelector("#profile-tab-badges")'),false)
  await evaluate('window.__profileFixture.settings({profileShowPlaytime:true,profileShowSteamStats:true});true')
  await click('#profile-tab-badges');assert.equal(await evaluate('document.querySelectorAll(".profile-badge").length'),2)
  await click('#profile-tab-overview');await key('ArrowRight')
  assert.equal(await evaluate('document.activeElement.id'),'profile-tab-games')
  await evaluate('window.__profileFixture.seed(90);true')
  assert.equal(await evaluate('document.querySelectorAll(".profile-game-tile").length'),36)
  await click('.profile-load-more');assert.equal(await evaluate('document.querySelectorAll(".profile-game-tile").length'),72)
  await click('#profile-tab-overview')
  for(const width of [850,600,400]){
    window.setSize(width,1000);await wait(160)
    assert.ok(await evaluate('(()=>{const root=document.querySelector(".profile-page");return root.scrollWidth<=root.clientWidth+1})()'),'No horizontal overflow at '+width)
    if(width===400)await capture('profile-mobile.png')
    await click('.profile-actions .profile-button-primary')
    assert.ok(await evaluate('(()=>{const d=document.querySelector("[role=dialog]"),r=d.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&d.scrollWidth<=d.clientWidth+1})()'))
    await key('Escape')
  }
  window.setSize(1400,1050)
  await evaluate('window.__profileFixture.friend("friend-a");true');await until('window.__profileFixture.social.waiting.has("friend-a")')
  await evaluate('window.__profileFixture.friend("friend-b");true');await until('window.__profileFixture.social.waiting.has("friend-b")')
  await evaluate('window.__profileFixture.social.resolve("friend-b",{username:"Correct friend",showPlaytime:false,showSteamStats:false,pinnedGames:[{id:"steam-620",name:"Portal 2",steamId:620}],totalLibraryCount:20,totalInstalledCount:2});true')
  await until('document.querySelector(".profile-name h1")?.textContent==="Correct friend"')
  await evaluate('window.__profileFixture.social.resolve("friend-a",{username:"Stale wrong friend"});true');await wait(150)
  assert.equal(await evaluate('document.querySelector(".profile-name h1").textContent'),'Correct friend')
  assert.equal(await evaluate('document.querySelectorAll(".profile-numbers strong").length'),2)
  await click('#profile-tab-games');await click('.profile-shared-filter')
  assert.equal(await evaluate('document.querySelector(".profile-shared-filter").getAttribute("aria-pressed")'),'true')
  assert.equal(await evaluate('document.querySelectorAll(".profile-game-tile").length'),1)
  await click('#profile-tab-overview')
  await click('.profile-actions .profile-button-primary')
  assert.equal(await evaluate('(window.__profileFixture.state().settings.eclipseFriends||[]).length'),0,'Failed requests cannot create fake local friends')
  await evaluate('window.__profileFixture.friend("missing");true');await until('window.__profileFixture.social.waiting.has("missing")')
  await evaluate('window.__profileFixture.social.resolve("missing",null);true');await until('!!document.querySelector("[data-profile-error]")')
  await click('[data-profile-error] button:last-child');await until('document.querySelector(".profile-name h1")?.textContent==="New profile name"')
  await evaluate('window.__profileFixture.settings({language:"en"});true')
  await until('document.querySelector("#profile-tab-overview").textContent==="Overview"')
  await capture('profile-english.png')
  await require('./profile-appearance-smoke.cjs')({window,evaluate,until,click,input,key,capture,writes,frameUrl,staticFrame,setSteam:value=>{steamFixture=value}})
  await require('./steam-frame-default-smoke.cjs')({evaluate,until,click,key,capture,frameUrl,steamReads})
  assert.deepEqual(errors,[])
  fs.writeFileSync(path.join(output,'verification.json'),JSON.stringify({search:true,pinsSaved:true,pinLimit:true,editorSave:true,saveFailureRecovery:true,escapeFocusRestore:true,checkboxFocus:true,playtimePrivacy:true,steamPrivacy:true,badges:true,keyboardTabs:true,sharedGames:true,progressiveGameList:true,responsive:true,staleProfilesIgnored:true,failedRequestCannotCreateFriend:true,missingProfile:true,localized:true,rendererErrors:errors},null,2))
  window.destroy();app.exit(0)
}).catch(async error=>{console.error(error);try{if(window&&!window.isDestroyed()){fs.writeFileSync(path.join(output,'failure.png'),(await window.webContents.capturePage()).toPNG());console.error(await window.webContents.executeJavaScript('document.body.innerText'))}}catch{}finally{app.exit(1)}})
setTimeout(()=>{console.error('Profile smoke test timeout');app.exit(1)},90000).unref()
