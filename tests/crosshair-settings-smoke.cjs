const assert=require('node:assert/strict')
module.exports=async({window,manager,evaluate,until,click,capture,settings,errors})=>{
  await until(()=>evaluate('!!document.querySelector("[data-crosshair-expand]")'))
  await click('[data-crosshair-expand]')
  assert.equal(await evaluate('document.querySelector(".crosshair-tabs [role=tab]").dataset.crosshairTab'),'library')
  assert.equal(await evaluate('document.querySelector("[data-crosshair-tab=library]").getAttribute("aria-selected")'),'true')
  await click('[data-crosshair-tab=presets]')
  await until(()=>evaluate('document.querySelectorAll("[data-crosshair-preset]").length===16'))
  await click('[data-crosshair-preset=x]')
  await until(()=>settings().crosshairConfig?.preset==='x')
  assert.equal(await evaluate('document.querySelector("[data-crosshair-preview] svg").dataset.crosshairStyle'),'x')
  await capture('crosshair-presets-de.png')
  await click('#overlay-scope-always')
  await click('#overlay-crosshair [role=switch]')
  await until(()=>evaluate('getComputedStyle(document.querySelector(".crosshair-section-icon")).color==="rgb(211, 167, 131)"'))
  const alignment=await evaluate(`(()=>{const a=document.querySelector('#overlay-crosshair [role=switch]').getBoundingClientRect(),b=document.querySelector('#overlay-performance-toggle [role=switch]').getBoundingClientRect(),icon=document.querySelector('.crosshair-section-icon');return{left:a.left-b.left,width:a.width-b.width,height:a.height-b.height,color:getComputedStyle(icon).color,active:icon.dataset.active}})()`)
  assert.deepEqual({left:alignment.left,width:alignment.width,height:alignment.height},{left:0,width:0,height:0},'Crosshair and neighboring switches must align exactly')
  assert.equal(alignment.active,'true');assert.equal(alignment.color,'rgb(211, 167, 131)')
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".crosshair-section-icon>svg")).filter'),'none')
  await until(()=>manager.getOverlayWindow()?.isVisible())
  const hud=manager.getOverlayWindow()
  await until(()=>hud.webContents.executeJavaScript('!!document.querySelector("#widget-crosshair svg")'))
  const equalRenderer=async()=>{
    const preview=await evaluate('document.querySelector("[data-crosshair-preview] svg").outerHTML'),actual=await hud.webContents.executeJavaScript('document.querySelector("#widget-crosshair svg").outerHTML')
    assert.equal(actual,preview,'Designer and native overlay must render identical geometry')
  }
  await equalRenderer()
  await click('[data-crosshair-tab=designer]')
  await click('[data-crosshair-shape=diamond]')
  await evaluate('(()=>{const input=document.querySelector("[data-crosshair-param=rotation]");Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,"value").set.call(input,"45");input.dispatchEvent(new Event("input",{bubbles:true}));input.dispatchEvent(new Event("change",{bubbles:true}));return true})()')
  await until(()=>settings().crosshairConfig?.rotation===45)
  await until(()=>hud.webContents.executeJavaScript('document.querySelector("#widget-crosshair svg g").getAttribute("transform").includes("rotate(45)")'))
  await equalRenderer()
  await capture('crosshair-designer-de.png')
  await click('[data-crosshair-tab=image]')
  await evaluate(`(async()=>{
    const canvas=document.createElement('canvas');canvas.width=64;canvas.height=64;const c=canvas.getContext('2d');c.strokeStyle='#101010';c.lineWidth=5;c.strokeRect(20,20,24,24);c.strokeStyle='#00ff88';c.lineWidth=2;c.strokeRect(20,20,24,24);c.fillStyle='white';c.fillRect(31,31,2,2);
    const blob=await new Promise(resolve=>canvas.toBlob(resolve,'image/png')),transfer=new DataTransfer();transfer.items.add(new File([blob],'custom-reticle.png',{type:'image/png'}));const input=document.querySelector('[data-crosshair-file]');input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));return true;
  })()`)
  await until(()=>settings().crosshairConfig?.mode==='image')
  await until(()=>hud.webContents.executeJavaScript('!!document.querySelector("#widget-crosshair svg image")'))
  assert.equal(settings().crosshairConfig.imageName,'custom-reticle.png')
  await equalRenderer()
  assert.ok(await evaluate('JSON.parse(localStorage.getItem("gamehub-store")).state.settings.crosshairConfig.imageData.startsWith("data:image/png;base64,")'))
  const image=settings().crosshairConfig.imageData
  await capture('crosshair-image-de.png')
  await evaluate(`(()=>{const transfer=new DataTransfer();transfer.items.add(new File(['<svg/>'],'invalid.png',{type:'image/png'}));const input=document.querySelector('[data-crosshair-file]');input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));return true})()`)
  await until(()=>evaluate('document.querySelector(".crosshair-error")?.textContent.includes("PNG")'))
  assert.equal(settings().crosshairConfig.imageData,image,'Invalid imports must preserve the working crosshair')
  await click('[data-crosshair-tab=designer]')
  await evaluate('(()=>{const input=document.querySelector("[data-crosshair-param=size]");Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,"value").set.call(input,"12");input.dispatchEvent(new Event("input",{bubbles:true}));input.dispatchEvent(new Event("change",{bubbles:true}));return true})()')
  await until(()=>settings().crosshairConfig.mode==='shape'&&settings().crosshairConfig.size===12)
  await click('[data-crosshair-tab=image]')
  await click('.crosshair-image-import .crosshair-action:not([data-crosshair-import])')
  await until(()=>settings().crosshairConfig.mode==='image')
  await equalRenderer()
  await evaluate('window.__overlaySettings.language("en");true')
  await until(()=>evaluate('document.querySelector(".crosshair-preview-heading strong").textContent==="Live preview"'))
  for(const width of [800,540,400]){window.setSize(width,920);await new Promise(resolve=>setTimeout(resolve,150));assert.ok(await evaluate('document.documentElement.scrollWidth<=innerWidth+1'),'The designer must fit narrow settings windows')}
  window.setSize(1120,920);await capture('crosshair-image-en.png')
  if(process.env.ECLIPSE_CROSSHAIR_LIBRARY_UI)await require('./crosshair-library-smoke.cjs').run({window,hud,evaluate,until,click,capture,settings})
  await click('#overlay-crosshair [role=switch]')
  await until(()=>!hud.isVisible())
  assert.deepEqual(errors,[])
  console.log('Crosshair designer passed: 16 presets, identical native SVG, live rotation, real PNG import, persistence, invalid-image rejection, English/German and narrow layouts')
}
